import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import * as api from './domainApi'
import { BusinessEntryForm } from './BusinessEntryForm'
import { confirmNavigation } from './navigationGuard'
import { HttpError } from './http'

vi.mock('./domainApi', () => ({ createDirectRecord: vi.fn(), listEntities: vi.fn(), listSpaces: vi.fn(), listRecords: vi.fn(), createEntity: vi.fn(), createSpace: vi.fn() }))
function fill(label: string, value: string) { fireEvent.change(screen.getByLabelText(label), { target: { value } }) }
function select(label: string, value: string) {
  fireEvent.click(screen.getByRole('combobox', { name: new RegExp(`^${label}：`) }))
  fireEvent.click(screen.getByRole('option', { name: value }))
}
async function chooseContext() {
  const spaces = screen.getByRole('button', { name: /^空间：/ })
  await waitFor(() => expect((spaces as HTMLButtonElement).disabled).toBe(false))
  fireEvent.click(spaces)
  fireEvent.click(screen.getByRole('checkbox', { name: '厨房' }))
  fireEvent.keyDown(document, { key: 'Escape' })
  select('装修阶段', '安装')
}
async function ledger(withContext = true) {
  const saved = vi.fn()
  render(<BusinessEntryForm kind="ledger" onSaved={saved} />)
  fireEvent.click(screen.getByRole('button', { name: '记一笔账' }))
  await waitFor(() => expect(screen.getByRole('combobox', { name: /^交易对象/ }).getAttribute('aria-disabled')).toBe('false'))
  fill('账目名称', '灯带尾款'); fill('金额（元）', '19.99'); fill('款项性质', '尾款')
  select('交易对象（收付款方）', '灯具店')
  if (withContext) await chooseContext()
  return saved
}
describe('业务页直接创建', () => {
  beforeEach(() => {
    vi.resetAllMocks()
    vi.mocked(api.listSpaces).mockResolvedValue([{ id: 'kitchen', name: '厨房', kind: 'room', parent_id: null } as api.SpaceEntry])
    vi.mocked(api.listRecords).mockResolvedValue([])
    vi.mocked(api.listEntities).mockImplementation(async kind => kind === 'vendors' ? [{ id: 'vendor', name: '灯具店' } as api.NamedEntity] : kind === 'stages' ? [{ id: 'stage', name: '安装' } as api.NamedEntity] : [])
    vi.mocked(api.createDirectRecord).mockResolvedValue({ id: 'new' } as api.DomainRecord)
  })
  it.each([['付款', 'payment', 'expense', 'paid'], ['退款', 'refund', 'refund', 'posted'], ['收入', 'income', 'income', 'posted']])('直接保存%s及准确金额', async (label, kind, direction, status) => {
    const saved = await ledger(); select('账目类型', label)
    fireEvent.click(screen.getByRole('button', { name: '保存账目' }))
    await screen.findByText('账目已保存')
    expect(api.createDirectRecord).toHaveBeenCalledWith(expect.objectContaining({ record_type: 'ledger', ledger_kind: kind, direction, status, amount_minor: 1999, currency: 'CNY', vendor_id: 'vendor', payment_kind: '尾款' }))
    expect(saved).toHaveBeenCalledOnce()
  })
  it('失败保留草稿，收起仍提醒离开，重试成功清理', async () => {
    vi.mocked(api.createDirectRecord).mockRejectedValueOnce(new Error('网络中断'))
    const saved = await ledger()
    fireEvent.click(screen.getByRole('button', { name: '保存账目' }))
    await screen.findByText('网络中断'); expect((screen.getByLabelText('账目名称') as HTMLInputElement).value).toBe('灯带尾款')
    select('装修阶段', '未选择')
    expect(screen.getByText('网络中断')).toBeTruthy()
    select('装修阶段', '安装')
    fireEvent.click(screen.getByRole('button', { name: '收起' }))
    const confirmation = vi.spyOn(window, 'confirm').mockReturnValue(false)
    expect(confirmNavigation()).toBe(false)
    fireEvent.click(screen.getByRole('button', { name: '记一笔账' }))
    await waitFor(() => expect((screen.getByRole('button', { name: '保存账目' }) as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByRole('button', { name: '保存账目' }))
    await screen.findByText('账目已保存'); expect(saved).toHaveBeenCalledOnce()
    expect(confirmNavigation()).toBe(true); confirmation.mockRestore()
  })
  it('拒绝三位小数，避免静默改变金额', async () => {
    await ledger(); fill('金额（元）', '1.001')
    fireEvent.click(screen.getByRole('button', { name: '保存账目' }))
    expect((await screen.findByRole('alert')).textContent).toContain('最多两位小数')
    expect(api.createDirectRecord).not.toHaveBeenCalled()
  })
  it.each(['ledger', 'issue'] as const)('%s 创建必须选择空间与阶段，拦截时保留草稿并定位常显字段', async kind => {
    if (kind === 'ledger') await ledger(false)
    else {
      render(<BusinessEntryForm kind="issue" onSaved={vi.fn()} />)
      fireEvent.click(screen.getByRole('button', { name: '新增待办或问题' }))
      fill('事项标题', '保留事项'); fill('事项内容', '保留现场情况')
    }
    const form = screen.getByRole('button', { name: kind === 'ledger' ? '保存账目' : '保存事项' }).closest('form')!
    const spaces = screen.getByRole('button', { name: /^空间：/ })
    await waitFor(() => expect((spaces as HTMLButtonElement).disabled).toBe(false))
    expect(spaces.textContent).toContain('请选择')
    expect(screen.getByRole('combobox', { name: /^装修阶段：/ }).getAttribute('aria-required')).toBe('true')
    fireEvent.submit(form)
    await screen.findByText('请选择至少一个空间')
    await waitFor(() => expect(document.activeElement).toBe(spaces))
    expect(api.createDirectRecord).not.toHaveBeenCalled()
    expect(screen.getByRole('button', { name: /更多信息与关联/ }).getAttribute('aria-expanded')).toBe('false')
    fireEvent.click(spaces); fireEvent.click(screen.getByRole('checkbox', { name: '厨房' })); fireEvent.keyDown(document, { key: 'Escape' })
    expect(screen.queryByText('请选择至少一个空间')).toBeNull()
    expect(screen.queryByText('请选择装修阶段')).toBeNull()
    fireEvent.submit(form)
    await screen.findByText('请选择装修阶段')
    await waitFor(() => expect(document.activeElement?.getAttribute('aria-label')).toBe('装修阶段：未选择'))
    expect((screen.getByLabelText(kind === 'ledger' ? '账目名称' : '事项标题') as HTMLInputElement).value).toBe(kind === 'ledger' ? '灯带尾款' : '保留事项')
    expect(api.createDirectRecord).not.toHaveBeenCalled()
    select('装修阶段', '安装')
    expect(screen.queryByText('请选择装修阶段')).toBeNull()
    expect((screen.getByLabelText(kind === 'ledger' ? '账目名称' : '事项标题') as HTMLInputElement).value).toBe(kind === 'ledger' ? '灯带尾款' : '保留事项')
    fireEvent.submit(form)
    await screen.findByText(kind === 'ledger' ? '账目已保存' : '待办与问题已保存')
    expect(api.createDirectRecord).toHaveBeenCalledWith(expect.objectContaining({ space_ids: ['kitchen'], stage_id: 'stage' }))
  })
  it('保存待办使用现有字段', async () => {
    const saved = vi.fn()
    render(<BusinessEntryForm kind="issue" onSaved={saved} />)
    fireEvent.click(screen.getByRole('button', { name: '新增待办或问题' }))
    fill('事项标题', '核对尺寸'); fill('事项内容', '与师傅核对柜内净宽'); fill('处理计划（可选）', '明天现场测量')
    await chooseContext()
    fireEvent.click(screen.getByRole('button', { name: '保存事项' }))
    await screen.findByText('待办与问题已保存')
    expect(api.createDirectRecord).toHaveBeenCalledWith(expect.objectContaining({ record_type: 'issue', status: 'pending', phenomenon: '与师傅核对柜内净宽', severity: 'medium', handling_plan: '明天现场测量' }))
  })
  it('待办就地新增四类档案，单选替换而多选保留已有空间', async () => {
    vi.mocked(api.createSpace).mockResolvedValue({ id: 'opening', name: '门洞', kind: 'component', parent_id: 'kitchen' })
    vi.mocked(api.createEntity).mockImplementation(async (type, payload) => ({ id: `new-${type}`, name: String(payload.name), ...payload }))
    render(<BusinessEntryForm kind="issue" onSaved={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: '新增待办或问题' }))
    fill('事项标题', '确认门洞尺寸')
    fill('事项内容', '同步新规格')
    await chooseContext()
    const addArchive = (role: 'button' | 'combobox', field: string, label: string, name: string) => {
      fireEvent.click(screen.getByRole(role, { name: text => text.startsWith(`${field}：`) }))
      fill(`搜索${field}`, name)
      fireEvent.click(screen.getByRole('button', { name: `新增${label}` }))
      return within(screen.getByRole('dialog', { name: `新增${label}` }))
    }
    const space = addArchive('button', '空间', '空间', '门洞')
    fireEvent.change(space.getByLabelText('空间类型'), { target: { value: 'component' } })
    fireEvent.change(space.getByLabelText('上级空间'), { target: { value: 'kitchen' } })
    fireEvent.click(space.getByRole('button', { name: '新增空间' }))
    await screen.findByRole('button', { name: /^空间：.*门洞/ })
    expect(api.createSpace).toHaveBeenCalledWith({ name: '门洞', kind: 'component', parent_id: 'kitchen' })
    const stage = addArchive('combobox', '装修阶段', '装修阶段', '收尾')
    fireEvent.click(stage.getByRole('button', { name: '新增装修阶段' }))
    await screen.findByRole('combobox', { name: '装修阶段：收尾' })
    fireEvent.click(screen.getByRole('button', { name: /更多信息与关联/ }))
    const material = addArchive('button', '材料', '材料', '门套')
    fireEvent.change(material.getByLabelText('型号（可选）'), { target: { value: 'A100' } })
    fireEvent.click(material.getByRole('button', { name: '新增材料' }))
    await screen.findByRole('button', { name: /^材料：.*门套/ })
    const participant = addArchive('button', '处理人', '参与人', '王师傅')
    fireEvent.click(participant.getByRole('button', { name: '新增参与人' }))
    await screen.findByRole('button', { name: /^处理人：.*王师傅/ })
    fireEvent.click(screen.getByRole('button', { name: '保存事项' }))
    await screen.findByText('待办与问题已保存')
    expect(api.createDirectRecord).toHaveBeenCalledWith(expect.objectContaining({
      title: '确认门洞尺寸', space_ids: ['kitchen', 'opening'], stage_id: 'new-stages',
      material_ids: ['new-materials'], participant_ids: ['new-participants'],
    }))
  })
  it('显式新增交易对象后选中，失败不清空名称', async () => {
    await ledger()
    vi.mocked(api.createEntity).mockRejectedValueOnce(new HttpError('名称保存失败', 500, 'save_failed')).mockResolvedValueOnce({ id: 'new-vendor', name: '新店' } as api.NamedEntity)
    fireEvent.click(screen.getByRole('combobox', { name: /^交易对象/ }))
    fill('搜索交易对象（收付款方）', '新店')
    fireEvent.click(screen.getByRole('button', { name: '新增商家' }))
    expect((screen.getByLabelText('商家名称') as HTMLInputElement).value).toBe('新店')
    fireEvent.click(screen.getByRole('button', { name: '新增商家' }))
    await screen.findByText('名称保存失败')
    expect((screen.getByLabelText('商家名称') as HTMLInputElement).value).toBe('新店')
    expect(api.createDirectRecord).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: '新增商家' }))
    await screen.findByRole('combobox', { name: '交易对象（收付款方）：新店' })
    fireEvent.click(screen.getByRole('button', { name: '保存账目' }))
    await screen.findByText('账目已保存')
    expect(api.createDirectRecord).toHaveBeenCalledWith(expect.objectContaining({ vendor_id: 'new-vendor' }))
  })
  it('可取消档案新增，查重后选用返回的档案并保留账目草稿', async () => {
    await ledger()
    vi.mocked(api.createEntity).mockRejectedValueOnce(new HttpError('重复档案', 409, 'archive_duplicate', {
      matches: [{ id: 'matched-vendor', name: '厨具店' }],
    }))
    const openArchive = () => {
      fireEvent.click(screen.getByRole('combobox', { name: /^交易对象/ }))
      fill('搜索交易对象（收付款方）', '厨具店')
      fireEvent.click(screen.getByRole('button', { name: '新增商家' }))
    }
    openArchive()
    fireEvent.click(screen.getByRole('button', { name: '取消' }))
    expect(screen.getByRole('combobox', { name: '交易对象（收付款方）：灯具店' })).toBeTruthy()
    openArchive()
    fireEvent.click(screen.getByRole('button', { name: '新增商家' }))
    fireEvent.click(await screen.findByRole('button', { name: '厨具店' }))
    expect(screen.getByRole('combobox', { name: '交易对象（收付款方）：厨具店' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '保存账目' }))
    await screen.findByText('账目已保存')
    expect(api.createDirectRecord).toHaveBeenCalledWith(expect.objectContaining({ vendor_id: 'matched-vendor', title: '灯带尾款', amount_minor: 1999 }))
  })
})

