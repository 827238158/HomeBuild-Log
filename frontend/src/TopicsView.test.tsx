import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import * as api from './topicsApi'
import * as domain from './domainApi'
import { TopicsView } from './TopicsView'
import { TopicSelect } from './TopicSelect'
import { confirmNavigation } from './navigationGuard'

vi.mock('./topicsApi', () => ({ listTopics: vi.fn(), getTopic: vi.fn(), createTopic: vi.fn(), updateTopic: vi.fn(), getTopicOverview: vi.fn(), getTopicActivities: vi.fn(), linkTopicRecord: vi.fn(), unlinkTopicRecord: vi.fn(), linkTopicPitfall: vi.fn(), unlinkTopicPitfall: vi.fn() }))
vi.mock('./domainApi', () => ({ listRecords: vi.fn(), listPitfalls: vi.fn() }))
const topic = (id: string, status: api.TopicStatus = 'active'): api.TopicDetail => ({ id, project_id: 'p', name: `规划${id}`, goal: '确定开关方案', current_situation: '正在确认零线', status, created_at: '2026-10-11T01:00:00Z', updated_at: '2026-10-11T01:00:00Z', records: [], pitfalls: [] })
const record = (id: string, type = 'issue'): domain.DomainRecord => ({ id, version: 1, record_type: type, title: `事项${id}`, status: 'pending', description: null, archived_at: null, source_refs: [] })
const pitfall: domain.PitfallEntry = { id: 'P', occurred_date: '2026-10-11', description: '安装后断连', status: 'unresolved', created_at: '2026-10-11T01:00:00Z', updated_at: '2026-10-11T01:00:00Z', resolutions: [] }
const activity = (id: string, overrides: Partial<api.TopicActivity> = {}): api.TopicActivity => ({ id, object_id: 'R', parent_id: null, object_kind: 'record', activity_kind: 'record', record_type: 'issue', title: `活动${id}`, content: '确认补线', occurred_at: '2026-10-11', date_missing: false, created_at: '2026-10-11T01:00:00Z', previous_status: null, next_status: null, ...overrides })
const actions = () => ({ onOpenRecord: vi.fn(), onOpenResearch: vi.fn(), onOpenPitfall: vi.fn(), onCreate: vi.fn() })
const choose = (label: string, option: string) => { fireEvent.click(screen.getByRole('combobox', { name: new RegExp(`^${label}：`) })); fireEvent.click(screen.getByRole('option', { name: option })) }
const openTopic = async (id = 'A', callbacks = actions()) => {
  render(<TopicsView {...callbacks} />)
  fireEvent.click(await screen.findByRole('button', { name: new RegExp(`规划${id}`) }))
  await screen.findByRole('heading', { name: `规划${id}` })
  return callbacks
}

beforeEach(() => {
  vi.clearAllMocks(); sessionStorage.clear()
  vi.spyOn(window, 'confirm').mockReturnValue(true)
  vi.mocked(api.listTopics).mockResolvedValue({ items: [topic('A'), topic('B')], summary: { total: 2, active: 2, archived: 0 } })
  vi.mocked(api.getTopic).mockImplementation(async id => topic(id))
  vi.mocked(api.getTopicOverview).mockResolvedValue({ pending_issues: [], recent_activities: [] })
  vi.mocked(api.getTopicActivities).mockResolvedValue({ items: [], total: 0 })
  vi.mocked(api.updateTopic).mockResolvedValue(topic('A'))
  vi.mocked(domain.listRecords).mockResolvedValue([record('R'), record('S', 'research')])
  vi.mocked(domain.listPitfalls).mockResolvedValue({ items: [pitfall], summary: { total: 1, unresolved: 1, resolved: 0 } })
})
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals() })

describe('主题管理', () => {
  it('搜索与状态使用服务端筛选', async () => {
    render(<TopicsView {...actions()} />)
    await screen.findByRole('button', { name: /规划A/ })
    fireEvent.change(screen.getByLabelText('搜索主题'), { target: { value: '开关' } })
    await waitFor(() => expect(api.listTopics).toHaveBeenLastCalledWith('开关', 'active'))
    choose('主题状态', '已归档')
    await waitFor(() => expect(api.listTopics).toHaveBeenLastCalledWith('开关', 'archived'))
  })
  it('新建失败保留输入，重试成功打开新主题', async () => {
    vi.mocked(api.createTopic).mockRejectedValueOnce(new Error('名称已存在')).mockResolvedValueOnce(topic('C'))
    render(<TopicsView {...actions()} />)
    fireEvent.click(screen.getByRole('button', { name: '新建主题' }))
    fireEvent.change(screen.getByLabelText('主题名称'), { target: { value: '  开关规划  ' } })
    fireEvent.change(screen.getByLabelText('当前情况（可选）'), { target: { value: '问了电工' } })
    fireEvent.click(screen.getByRole('button', { name: '创建主题' }))
    await screen.findByText('名称已存在')
    expect((screen.getByLabelText('主题名称') as HTMLInputElement).value).toBe('  开关规划  ')
    fireEvent.click(screen.getByRole('button', { name: '创建主题' }))
    await screen.findByRole('heading', { name: '规划C' })
    expect(api.createTopic).toHaveBeenLastCalledWith({ name: '开关规划', goal: '', current_situation: '问了电工' })
    expect(sessionStorage.getItem('homebuild:topic:new:draft')).toBeNull()
  })
  it('编辑失败保留草稿，成功刷新当前情况', async () => {
    vi.mocked(api.updateTopic).mockRejectedValueOnce(new Error('保存失败'))
    await openTopic()
    fireEvent.click(screen.getByRole('button', { name: '编辑主题' }))
    fireEvent.change(screen.getByLabelText('当前情况（可选）'), { target: { value: '零线已确认' } })
    fireEvent.click(screen.getByRole('button', { name: '保存主题' }))
    await screen.findByText('保存失败')
    expect((screen.getByLabelText('当前情况（可选）') as HTMLTextAreaElement).value).toBe('零线已确认')
    vi.mocked(api.updateTopic).mockResolvedValue(topic('A'))
    vi.mocked(api.getTopic).mockResolvedValue({ ...topic('A'), current_situation: '零线已确认' })
    fireEvent.click(screen.getByRole('button', { name: '保存主题' }))
    await waitFor(() => expect(screen.queryByLabelText('当前情况（可选）')).toBeNull())
    await screen.findByText('零线已确认')
  })
  it('概览展示未完成待办、最近进展和未知日期', async () => {
    vi.mocked(api.getTopicOverview).mockResolvedValue({ pending_issues: [record('R')], recent_activities: [activity('1', { date_missing: true })] })
    const callbacks = await openTopic()
    expect(screen.getByText('正在确认零线')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '事项R' }))
    expect(callbacks.onOpenRecord).toHaveBeenCalledWith('R')
    expect(screen.getByText('日期待补充')).toBeTruthy()
  })
  it('时间线按类型筛选与每页30条分页', async () => {
    vi.mocked(api.getTopicActivities).mockResolvedValue({ items: [activity('1')], total: 35 })
    await openTopic()
    await screen.findByText('1–30 / 35 条')
    fireEvent.click(screen.getByRole('button', { name: '下一页' }))
    await waitFor(() => expect(api.getTopicActivities).toHaveBeenLastCalledWith('A', '', 30, 30))
    choose('时间线类型', '调研')
    await waitFor(() => expect(api.getTopicActivities).toHaveBeenLastCalledWith('A', 'research', 0, 30))
  })
  it('子过程打开父调研或踩坑；从主题创建预选当前主题', async () => {
    vi.mocked(api.getTopicActivities).mockResolvedValue({ items: [activity('research', { object_kind: 'research_entry', object_id: 'E', parent_id: 'S', record_type: 'research' }), activity('pitfall', { object_kind: 'pitfall_resolution', object_id: 'H', parent_id: 'P', record_type: 'pitfall' })], total: 2 })
    const callbacks = await openTopic()
    fireEvent.click(await screen.findByRole('button', { name: '活动research' }))
    expect(callbacks.onOpenResearch).toHaveBeenCalledWith('S')
    fireEvent.click(screen.getByRole('button', { name: '活动pitfall' }))
    expect(callbacks.onOpenPitfall).toHaveBeenCalledWith('P')
    fireEvent.click(screen.getByRole('button', { name: '新增待办' }))
    expect(callbacks.onCreate).toHaveBeenCalledWith('issue', 'A')
  })
  it('关联已有正式记录与踩坑，解除关联仅调用归属接口', async () => {
    const linked = { ...topic('A'), records: [record('R')], pitfalls: [pitfall] }
    vi.mocked(api.linkTopicRecord).mockResolvedValue(linked)
    vi.mocked(api.linkTopicPitfall).mockResolvedValue(linked)
    vi.mocked(api.unlinkTopicRecord).mockResolvedValue(topic('A'))
    await openTopic()
    fireEvent.click(screen.getByRole('button', { name: '关联已有内容' }))
    fireEvent.click(await screen.findByRole('button', { name: '关联：事项R' }))
    await waitFor(() => expect(api.linkTopicRecord).toHaveBeenCalledWith('A', 'R', 1))
    fireEvent.click(screen.getByRole('button', { name: '关联：安装后断连' }))
    await waitFor(() => expect(api.linkTopicPitfall).toHaveBeenCalledWith('A', 'P'))
    vi.mocked(api.getTopic).mockResolvedValue(linked)
    fireEvent.click(screen.getByRole('button', { name: '关联：事项S' }))
    await screen.findByRole('button', { name: '解除关联：事项R' })
    fireEvent.click(screen.getByRole('button', { name: '解除关联：事项R' }))
    await waitFor(() => expect(api.unlinkTopicRecord).toHaveBeenCalledWith('A', 'R', 1))
  })
  it('已归档主题禁止新增与关联，允许解除归属与恢复', async () => {
    vi.mocked(api.getTopic).mockResolvedValue({ ...topic('A', 'archived'), records: [record('R')] })
    await openTopic()
    expect((screen.getByRole('button', { name: '新增待办' }) as HTMLButtonElement).disabled).toBe(true)
    expect((screen.getByRole('button', { name: '关联已有内容' }) as HTMLButtonElement).disabled).toBe(true)
    expect((screen.getByRole('button', { name: '解除关联：事项R' }) as HTMLButtonElement).disabled).toBe(false)
    fireEvent.click(screen.getByRole('button', { name: '恢复主题' }))
    await waitFor(() => expect(api.updateTopic).toHaveBeenCalledWith('A', { status: 'active' }))
  })
  it('过期主题详情失败不会影响新主题', async () => {
    let fail!: (error: Error) => void
    vi.mocked(api.getTopic).mockImplementation(id => id === 'A' ? new Promise((_, reject) => { fail = reject }) : Promise.resolve(topic(id)))
    render(<TopicsView {...actions()} />)
    fireEvent.click(await screen.findByRole('button', { name: /规划A/ }))
    await waitFor(() => expect(api.getTopic).toHaveBeenCalledWith('A'))
    fireEvent.click(screen.getByRole('button', { name: /规划B/ }))
    await screen.findByRole('heading', { name: '规划B' })
    await act(async () => fail(new Error('A读取失败')))
    expect(screen.queryByText('A读取失败')).toBeNull()
  })
  it('概览失败仍显示主题主体与时间线，并可重试', async () => {
    vi.mocked(api.getTopicOverview).mockRejectedValueOnce(new Error('概览读取失败'))
    vi.mocked(api.getTopicActivities).mockResolvedValue({ items: [activity('1')], total: 1 })
    await openTopic()
    await screen.findByText('概览读取失败')
    expect(screen.getByText('正在确认零线')).toBeTruthy()
    expect(screen.getByRole('button', { name: '活动1' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '重试读取概览' }))
    await screen.findByText('暂无未完成待办。')
  })
  it('隐藏主题页面不保留未保存输入的导航拦截', async () => {
    const callbacks = actions()
    const view = render(<TopicsView {...callbacks} />)
    fireEvent.click(screen.getByRole('button', { name: '新建主题' }))
    fireEvent.change(screen.getByLabelText('主题名称'), { target: { value: '新方案' } })
    view.rerender(<TopicsView {...callbacks} active={false} />)
    expect(confirmNavigation()).toBe(true)
    expect(window.confirm).not.toHaveBeenCalled()
    view.rerender(<TopicsView {...callbacks} active />)
    confirmNavigation()
    expect(window.confirm).toHaveBeenCalled()
  })
  it('外部业务修改revision刷新主题和时间线且保持选择', async () => {
    const callbacks = actions()
    const view = render(<TopicsView {...callbacks} />)
    fireEvent.click(await screen.findByRole('button', { name: /规划B/ }))
    await screen.findByRole('heading', { name: '规划B' })
    vi.mocked(api.getTopic).mockClear(); vi.mocked(api.getTopicActivities).mockClear()
    view.rerender(<TopicsView {...callbacks} revision={1} />)
    await waitFor(() => expect(api.getTopic).toHaveBeenCalledWith('B'))
    expect(api.getTopicActivities).toHaveBeenCalledWith('B', '', 0, 30)
    expect(screen.getByRole('heading', { name: '规划B' })).toBeTruthy()
  })
})

describe('可选多主题归属', () => {
  it('已归档归属可移除，但未选归档主题不能新增', async () => {
    vi.mocked(api.listTopics).mockResolvedValue({ items: [topic('A'), topic('B', 'archived'), topic('C', 'archived')], summary: { total: 3, active: 1, archived: 2 } })
    const onChange = vi.fn()
    render(<TopicSelect value={['B']} onChange={onChange} />)
    await waitFor(() => expect(api.listTopics).toHaveBeenCalled())
    fireEvent.click(screen.getByRole('button', { name: /所属主题/ }))
    const b = await screen.findByRole('checkbox', { name: '规划B' })
    expect((b as HTMLInputElement).disabled).toBe(false)
    expect((screen.getByRole('checkbox', { name: '规划C' }) as HTMLInputElement).disabled).toBe(true)
    fireEvent.click(b)
    expect(onChange).toHaveBeenCalledWith([])
  })
  it('加载失败重试不清空原归属，Escape关闭菜单恢复入口', async () => {
    vi.mocked(api.listTopics).mockRejectedValueOnce(new Error('主题读取失败')).mockResolvedValueOnce({ items: [topic('A')], summary: { total: 1, active: 1, archived: 0 } })
    const onChange = vi.fn()
    render(<TopicSelect value={['A']} onChange={onChange} />)
    const trigger = screen.getByRole('button', { name: /所属主题/ })
    fireEvent.click(trigger)
    await screen.findByText('主题读取失败')
    fireEvent.click(screen.getByRole('button', { name: '重试' }))
    await screen.findByRole('checkbox', { name: '规划A' })
    expect(onChange).not.toHaveBeenCalled()
    fireEvent.keyDown(document, { key: 'Escape' })
    expect(screen.queryByRole('listbox')).toBeNull()
    expect(document.activeElement).toBe(trigger)
  })
  it('公共下拉互斥防止两个多选菜单同时打开', async () => {
    render(<><TopicSelect value={[]} label="主题一" onChange={vi.fn()} /><TopicSelect value={[]} label="主题二" onChange={vi.fn()} /></>)
    fireEvent.click(screen.getByRole('button', { name: /主题一：/ }))
    await screen.findByRole('listbox', { name: '主题一' })
    fireEvent.click(screen.getByRole('button', { name: /主题二：/ }))
    expect(screen.queryByRole('listbox', { name: '主题一' })).toBeNull()
    expect(within(screen.getByRole('listbox', { name: '主题二' })).getByRole('checkbox', { name: '规划A' })).toBeTruthy()
  })
})
